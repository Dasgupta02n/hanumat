function pack(deity, title, scenes) {
  if (scenes.length !== 108) throw new Error(`${deity} scenes ${scenes.length}`);
  if (STYLES.length !== 108) throw new Error(`styles ${STYLES.length}`);
  const images = scenes.map(([leela, hi, en], i) => {
    const id = String(i + 1).padStart(3, "0");
    return {
      id,
      file: `${id}.jpg`,
      style: STYLES[i],
      scene: { hi, en },
      leela,
    };
  });
  return {
    id: `${deity}-108-leela`,
    title,
    notes:
      "Devotional digital folk painting. Not classical murti photography. One unique Indian folk/miniature/mural style per leela.",
    images,
  };
}

